create table if not exists public.ad_performance_reports (
  id bigint generated by default as identity primary key,
  client_id text not null references public.clients(id) on delete cascade,
  report_date date not null default current_date,
  period_start date not null,
  period_end date not null,
  report_status text not null default 'Activa'
    check (report_status in ('Activa', 'Requiere atención', 'Pausada')),
  spend numeric(12,2) not null default 0 check (spend >= 0),
  impressions integer not null default 0 check (impressions >= 0),
  reach integer not null default 0 check (reach >= 0),
  clicks integer not null default 0 check (clicks >= 0),
  ctr numeric(8,2) not null default 0 check (ctr >= 0),
  cpc numeric(12,2) not null default 0 check (cpc >= 0),
  leads integer not null default 0 check (leads >= 0),
  cpl numeric(12,2) not null default 0 check (cpl >= 0),
  appointments integer not null default 0 check (appointments >= 0),
  cost_per_appointment numeric(12,2) not null default 0 check (cost_per_appointment >= 0),
  summary text not null default '' check (char_length(summary) <= 5000),
  wins text not null default '' check (char_length(wins) <= 5000),
  issues text not null default '' check (char_length(issues) <= 5000),
  next_steps text not null default '' check (char_length(next_steps) <= 5000),
  created_by uuid not null default auth.uid() references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (client_id, report_date),
  check (period_end >= period_start)
);

alter table public.ad_performance_reports enable row level security;
