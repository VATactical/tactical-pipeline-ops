create or replace function private.validate_ads_report_client_status()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.clients
    where id = new.client_id and status in ('ADS LIVE', 'ADS PAUSED')
  ) then
    raise exception 'ADS reports are available only after a campaign is active';
  end if;
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function private.validate_ads_report_client_status() from public, anon, authenticated;
drop trigger if exists validate_ads_report_client_status on public.ad_performance_reports;
create trigger validate_ads_report_client_status
before insert or update on public.ad_performance_reports
for each row execute function private.validate_ads_report_client_status();

