create table if not exists public.time_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  eod_report_id bigint references public.eod_reports(id) on delete set null,
  work_date date not null,
  hours numeric(5,2) not null check (hours > 0 and hours <= 24),
  memo text not null check (char_length(btrim(memo)) between 1 and 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.time_entries enable row level security;
revoke all on public.time_entries from anon, authenticated;
grant select, insert, update, delete on public.time_entries to authenticated;
grant usage, select on sequence public.time_entries_id_seq to authenticated;

create policy "Users read own time; operations admins read all"
on public.time_entries for select to authenticated
using (user_id = (select auth.uid()) or (select private.has_permission('operations_admin')));

create policy "Users create own time"
on public.time_entries for insert to authenticated
with check (user_id = (select auth.uid()) and (select private.has_permission('eod_reports')));

create policy "Users update own time"
on public.time_entries for update to authenticated
using (user_id = (select auth.uid()) and (select private.has_permission('eod_reports')))
with check (user_id = (select auth.uid()) and (select private.has_permission('eod_reports')));

create policy "Users delete own time"
on public.time_entries for delete to authenticated
using (user_id = (select auth.uid()) and (select private.has_permission('eod_reports')));

create index if not exists time_entries_user_work_date_idx
  on public.time_entries(user_id, work_date desc);
create index if not exists time_entries_report_idx
  on public.time_entries(eod_report_id)
  where eod_report_id is not null;

create table if not exists public.note_reads (
  note_id bigint not null references public.notes(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  seen_at timestamptz not null default now(),
  visible_until timestamptz not null default (now() + interval '24 hours'),
  primary key (note_id, user_id),
  check (visible_until >= seen_at)
);

