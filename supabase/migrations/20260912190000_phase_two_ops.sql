create or replace function private.schedule_calendar_notifications()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  reminder integer;
  member record;
begin
  if tg_op = 'UPDATE' then
    delete from public.notifications
    where source_type = 'calendar_event' and source_id = new.id::text and read_at is null;
  end if;

  foreach reminder in array new.reminder_minutes loop
    for member in select id from public.profiles where active loop
      insert into public.notifications (recipient_id, title, body, source_type, source_id, notify_at)
      values (
        member.id,
        case new.event_type when 'Reunión' then 'Próxima reunión' else 'Próximo evento' end,
        new.title,
        'calendar_event',
        new.id::text,
        new.start_at - make_interval(mins => reminder)
      )
      on conflict do nothing;
    end loop;
  end loop;
  return new;
end;
$$;

revoke all on function private.schedule_calendar_notifications() from public, anon, authenticated;
drop trigger if exists calendar_event_notifications on public.calendar_events;
create trigger calendar_event_notifications after insert or update on public.calendar_events
  for each row execute function private.schedule_calendar_notifications();

