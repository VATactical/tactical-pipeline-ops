create or replace function private.set_task_timestamps()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  if new.status = 'Completada' and old.status is distinct from 'Completada' then
    new.completed_at = now();
  elsif new.status <> 'Completada' then
    new.completed_at = null;
  end if;
  return new;
end;
$$;

