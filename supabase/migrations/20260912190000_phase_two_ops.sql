create or replace function private.has_permission(permission_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select role = 'superadmin' or coalesce((permissions ->> permission_name)::boolean, false)
     from public.profiles
     where id = (select auth.uid()) and active),
    false
  );
$$;

revoke all on function private.has_permission(text) from public, anon;
grant execute on function private.has_permission(text) to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name, permissions)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    '{"clients_create":true,"clients_edit":true,"tasks_create":false,"calendar_manage":true,"eod_reports":true,"users_manage":false}'::jsonb
  );
  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

